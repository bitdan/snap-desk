//! macOS 剪贴板：NSPasteboard 没有变更通知，只能轮询 changeCount。
//! 轮询线程只发送有界唤醒，读取、解码和 SQL 仍由存储工作线程完成，与 Windows 分工一致。
use super::super::{model::ClipboardSettings, reader::Snapshot};
use crate::macos::{self, array_items, data_bytes, ns_array, ns_string, rust_string, Id};
use objc2::{class, msg_send, runtime::Bool};
use std::{
    sync::{
        atomic::{AtomicBool, Ordering},
        mpsc::SyncSender,
        Arc,
    },
    thread::JoinHandle,
    time::Duration,
};

/// 轮询间隔：复制后约 0.25 秒内入库；计数读取是一次进程内调用，开销可忽略。
const POLL: Duration = Duration::from_millis(250);

/// nspasteboard.org 约定的保密/临时标记：密码管理器、一次性验证码等写入时附带，不记录。
const SKIP_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

pub struct Watcher {
    stop: Arc<AtomicBool>,
    worker: Option<JoinHandle<()>>,
}
impl Watcher {
    pub fn start(tx: SyncSender<()>) -> Result<Self, String> {
        let stop = Arc::new(AtomicBool::new(false));
        let stopped = stop.clone();
        let worker = std::thread::Builder::new()
            .name("clipboard-poll".into())
            .spawn(move || {
                let mut last = macos::pasteboard_change_count();
                while !stopped.load(Ordering::Acquire) {
                    std::thread::sleep(POLL);
                    let current = macos::pasteboard_change_count();
                    if current != last {
                        last = current;
                        // 队列已满说明工作线程尚未处理上一次唤醒，它会读到最新内容，丢弃即可。
                        let _ = tx.try_send(());
                    }
                }
            })
            .map_err(|_| "无法启动剪贴板监听线程。")?;
        Ok(Self {
            stop,
            worker: Some(worker),
        })
    }
}
impl Drop for Watcher {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(worker) = self.worker.take() {
            let _ = worker.join();
        }
    }
}

pub fn sequence() -> u32 {
    macos::pasteboard_change_count()
}

/// 读取顺序与 Windows 一致：文件引用优先，其次 PNG / TIFF 图片，最后纯文本。
pub fn snapshot(settings: &ClipboardSettings) -> Result<Option<Snapshot>, String> {
    // 名单为空时不查询；取写入者需要私有接口，因此按前台应用判断，与 Windows 的回退路径一致。
    if !settings.excluded_apps.is_empty()
        && macos::frontmost_executable().is_some_and(|name| settings.excludes(&name))
    {
        return Ok(None);
    }
    objc2::rc::autoreleasepool(|_| unsafe {
        let pasteboard: Id = msg_send![class!(NSPasteboard), generalPasteboard];
        let skip: Vec<Id> = SKIP_TYPES.iter().map(|t| ns_string(t)).collect();
        let marked: Id = msg_send![pasteboard, availableTypeFromArray: ns_array(&skip)];
        if !marked.is_null() {
            return Ok(None);
        }
        let paths = file_paths(pasteboard);
        if !paths.is_empty() {
            if !settings.save_copied_files {
                return Ok(None);
            }
            super::super::files::validate(&paths)?;
            return Ok(Some(Snapshot::Paths(paths)));
        }
        if let Some(png) = image_png(pasteboard, settings)? {
            if !settings.save_copied_images {
                return Ok(None);
            }
            return Ok(Some(Snapshot::Png(png)));
        }
        let text: Id = msg_send![pasteboard, stringForType: ns_string("public.utf8-plain-text")];
        if text.is_null() {
            return Ok(None);
        }
        if !settings.save_copied_text {
            return Ok(None);
        }
        // NSUTF8StringEncoding = 4；先比较字节数，超限时不复制正文。
        let bytes: usize = msg_send![text, lengthOfBytesUsingEncoding: 4usize];
        if bytes > settings.max_text_bytes as usize {
            return Err("文本超过历史大小限制，未记录。".into());
        }
        Ok(rust_string(text).map(Snapshot::Utf8))
    })
}

/// 每个剪贴板条目最多一个文件 URL；`path` 已完成百分号解码。
unsafe fn file_paths(pasteboard: Id) -> Vec<String> {
    let items: Id = msg_send![pasteboard, pasteboardItems];
    let file_url = ns_string("public.file-url");
    array_items(items)
        .into_iter()
        .filter_map(|item| {
            let value: Id = msg_send![item, stringForType: file_url];
            if value.is_null() {
                return None;
            }
            let url: Id = msg_send![class!(NSURL), URLWithString: value];
            if url.is_null() {
                return None;
            }
            let path: Id = msg_send![url, path];
            rust_string(path)
        })
        .collect()
}

/// PNG 直接使用；只有 TIFF 时（截图、预览等常见）交给系统转为 PNG。
/// 两条路径都先按像素数限额检查，再分配完整位图。
unsafe fn image_png(pasteboard: Id, settings: &ClipboardSettings) -> Result<Option<Vec<u8>>, String> {
    const LIMIT: usize = 64 * 1024 * 1024;
    let too_large = || "剪贴板内容超过单项大小限制，未记录。".to_string();
    let png: Id = msg_send![pasteboard, dataForType: ns_string("public.png")];
    if let Some(bytes) = data_bytes(png, LIMIT).map_err(|_| too_large())? {
        let (width, height) = png_dimensions(&bytes)?;
        check_pixels(width, height, settings)?;
        return Ok(Some(bytes));
    }
    let tiff: Id = msg_send![pasteboard, dataForType: ns_string("public.tiff")];
    if tiff.is_null() {
        return Ok(None);
    }
    let length: usize = msg_send![tiff, length];
    if length > LIMIT {
        return Err(too_large());
    }
    let rep: Id = msg_send![class!(NSBitmapImageRep), imageRepWithData: tiff];
    if rep.is_null() {
        return Err("剪贴板图片编码无效。".into());
    }
    let width: isize = msg_send![rep, pixelsWide];
    let height: isize = msg_send![rep, pixelsHigh];
    check_pixels(width.max(0) as u32, height.max(0) as u32, settings)?;
    let properties: Id = msg_send![class!(NSDictionary), dictionary];
    // NSBitmapImageFileTypePNG = 4。
    let encoded: Id = msg_send![rep, representationUsingType: 4usize, properties: properties];
    data_bytes(encoded, LIMIT)
        .map_err(|_| too_large())?
        .ok_or_else(|| "剪贴板图片转换失败。".into())
        .map(Some)
}

fn check_pixels(width: u32, height: u32, settings: &ClipboardSettings) -> Result<(), String> {
    if width == 0
        || height == 0
        || u64::from(width) * u64::from(height) > u64::from(settings.max_image_pixels)
    {
        return Err("图片超过历史像素限制，未记录。".into());
    }
    Ok(())
}

fn png_dimensions(bytes: &[u8]) -> Result<(u32, u32), String> {
    if bytes.len() >= 24 && &bytes[..8] == b"\x89PNG\r\n\x1a\n" && &bytes[12..16] == b"IHDR" {
        return Ok((
            u32::from_be_bytes(bytes[16..20].try_into().unwrap()),
            u32::from_be_bytes(bytes[20..24].try_into().unwrap()),
        ));
    }
    Err("剪贴板图片头无效，未记录。".into())
}

/// 写回文件引用（file URL），粘贴到访达时为复制而非移动。
pub fn write_files(paths: &[String]) -> Result<(), String> {
    super::super::files::validate(paths)?;
    for path in paths {
        if std::fs::metadata(path).is_err() {
            return Err(format!("原文件已移动、删除或不可访问，无法复制：{path}"));
        }
    }
    objc2::rc::autoreleasepool(|_| unsafe {
        let urls: Vec<Id> = paths
            .iter()
            .map(|path| {
                let url: Id = msg_send![class!(NSURL), fileURLWithPath: ns_string(path)];
                url
            })
            .collect();
        if urls.iter().any(|url| url.is_null()) {
            return Err("复制文件引用失败，请重试。".into());
        }
        let pasteboard: Id = msg_send![class!(NSPasteboard), generalPasteboard];
        let _: isize = msg_send![pasteboard, clearContents];
        let written: Bool = msg_send![pasteboard, writeObjects: ns_array(&urls)];
        if written.as_bool() {
            Ok(())
        } else {
            Err("复制文件引用失败，请重试。".into())
        }
    })
}

/// 唤出剪贴板窗口前的前台应用进程号；属于本程序或读取失败时返回 0。
pub fn foreground_window() -> usize {
    match macos::frontmost_pid() {
        Some(pid) if pid as u32 != std::process::id() => pid as usize,
        _ => 0,
    }
}

pub fn activate(target: usize) -> Result<(), String> {
    if macos::activate_pid(target as i32) {
        Ok(())
    } else {
        Err("原应用已退出，内容已复制，可手动粘贴。".into())
    }
}

/// 等原应用回到前台、且 ⇧⌃⌥ 与回车已松开，再注入 ⌘V；⌘ 仍按着不影响结果。
pub fn send_paste(target: usize) -> Result<(), String> {
    use std::time::Instant;
    let deadline = Instant::now() + Duration::from_secs(1);
    loop {
        let front = macos::frontmost_pid() == Some(target as i32);
        let held = macos::modifier_flags()
            & (macos::FLAG_SHIFT | macos::FLAG_CONTROL | macos::FLAG_OPTION)
            != 0
            || macos::key_down(macos::KEY_RETURN)
            || macos::key_down(macos::KEY_V);
        if front && !held {
            break;
        }
        if Instant::now() >= deadline {
            return Err(if front {
                "请松开按键后重试，内容已复制，可手动粘贴。".into()
            } else {
                "未能回到原窗口，内容已复制，可手动粘贴。".into()
            });
        }
        std::thread::sleep(Duration::from_millis(15));
    }
    macos::post_command_key(macos::KEY_V)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn png_header_is_checked_before_decoding() {
        assert!(png_dimensions(b"PNG").is_err());
        let mut header = b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR".to_vec();
        header.extend_from_slice(&640u32.to_be_bytes());
        header.extend_from_slice(&480u32.to_be_bytes());
        assert_eq!(png_dimensions(&header).unwrap(), (640, 480));
        let settings = ClipboardSettings {
            max_image_pixels: 100,
            ..ClipboardSettings::default()
        };
        assert!(check_pixels(640, 480, &settings).is_err());
        assert!(check_pixels(10, 10, &settings).is_ok());
    }
}
